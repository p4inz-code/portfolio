function check(q: string, expect: string, ctx?: string): 'ok' | 'miss' | 'wrong' {
  const e = ctx ? matchWithContext(entries, q, ctx) : matchFaq(entries, q);
  const options = expect.split('|');
  if (!e) return options.includes('-') ? 'ok' : 'miss';
  const hit = options.some((o) => (o.endsWith(':') ? e.project === o.slice(0, -1) : o.endsWith('*') ? e.id.startsWith(o.slice(0, -1)) : o === e.id));
  return hit ? 'ok' : 'wrong';
}

test(`holdout interview: ${ROWS.length} unseen questions, zero wrong answers`, (t) => {
  assert.ok(ROWS.length >= 500, `holdout too small: ${ROWS.length}`);
  const wrong: string[] = [];
  const miss: string[] = [];
  let ok = 0;
  for (const [q, expect, ctx] of ROWS) {
    const v = check(q, expect, ctx);
    if (v === 'ok') ok++;
    else {
      const got = (ctx ? matchWithContext(entries, q, ctx) : matchFaq(entries, q))?.id ?? 'nothing';
      (v === 'wrong' ? wrong : miss).push(`${JSON.stringify(q)} -> ${got}   (accepted: ${expect})`);
    }
  }
  console.log(`\nHOLDOUT: ${ROWS.length} questions | correct ${ok} (${((ok / ROWS.length) * 100).toFixed(1)}%) | misses ${miss.length} | WRONG ${wrong.length}`);
  if (wrong.length) console.log(`\nWRONG:\n${wrong.join('\n')}`);
  if (miss.length) console.log(`\nMISSES (the AI tier answers these):\n${miss.join('\n')}`);
  t.diagnostic(`${ok}/${ROWS.length} correct`);
  const unknown = ROWS.flatMap(([, ex]) => ex.split('|')).filter((o) => o !== '-' && !o.endsWith(':') && !(o.endsWith('*') ? [...ids].some((i) => i.startsWith(o.slice(0, -1))) : ids.has(o)));
  assert.deepEqual([...new Set(unknown)], [], 'expectation names an id that does not exist');
  assert.equal(wrong.length, 0, `${wrong.length} wrong answers`);
  assert.ok(miss.length <= ROWS.length * 0.1, `${miss.length} misses is more than 10% of the holdout`);
});
